CREATE TABLE pushcash_test.clients (
	id int4 NOT NULL,
	"name" varchar(255) NOT NULL,
	email varchar(255) NOT NULL,
	property varchar(255) NOT NULL,
	logo_svg bytea NOT NULL,
	created_at timestamp NULL DEFAULT now(),
	billing_enabled bool NOT NULL DEFAULT false,
	maximum_guarantee int4 NULL,
	pricing_schedule jsonb NULL,
	limits_configuration jsonb NULL,
	CONSTRAINT clients_pkey PRIMARY KEY (id)
);

CREATE TABLE pushcash_test.disputes (
	id varchar(255) NOT NULL,
	client_id int4 NOT NULL,
	intent_id varchar(255) NULL,
	created_at timestamp NOT NULL,
	status varchar(255) NULL,
	code varchar(4) NULL,
	amount int4 NOT NULL,
	currency varchar(3) NOT NULL,
	CONSTRAINT disputes_pkey PRIMARY KEY (id)
);

CREATE TABLE pushcash_test.intents (
	id varchar(255) NOT NULL,
	client_id int4 NOT NULL,
	user_id varchar(255) NULL,
	amount int4 NOT NULL,
	direction varchar(8) NULL,
	currency varchar(3) NULL,
	status varchar(255) NULL,
	created_at timestamp NULL DEFAULT now(),
	batch_id bpchar(8) NULL,
	transaction_number numeric(10) NULL,
	received_file_id int4 NULL,
	display_loyalty bool NULL DEFAULT false,
	display_limits bool NULL DEFAULT false,
	limits_request_id int4 NULL,
	payment_credential_id int4 NULL,
	processed_date date NULL,
	processor varchar(32) NULL DEFAULT NULL::character varying,
	mx_aggregation_type varchar(255) NULL DEFAULT NULL::character varying,
	mx_aggregation_result varchar(255) NULL DEFAULT NULL::character varying,
	mx_aggregation_started_at timestamp NULL,
	rail varchar(255) NULL,
	guarantee_amount int4 NULL,
	virtual_account_id varchar(255) NOT NULL,
	redirect_url varchar(255) NULL,
	idempotency_key varchar(255) NOT NULL,
	approval_mode_manual bool NOT NULL DEFAULT false,
	CONSTRAINT intents_check CHECK ((guarantee_amount <= amount)),
	CONSTRAINT intents_direction_check CHECK (((direction)::text = ANY (ARRAY[('cash_in'::character varying)::text, ('cash_out'::character varying)::text]))),
	CONSTRAINT intents_guarantee_amount_check CHECK ((guarantee_amount >= 0)),
	CONSTRAINT intents_pkey PRIMARY KEY (id)
);

CREATE TABLE pushcash_test.users (
	id varchar(255) NOT NULL,
	client_id int4 NOT NULL,
	status varchar(255) NOT NULL,
	first_name varchar(255) NOT NULL,
	email varchar(255) NOT NULL,
	phone_number varchar(255) NOT NULL,
	created_at timestamp NULL DEFAULT now(),
	daily_limit int4 NULL DEFAULT 500000,
	has_displayed_loyalty bool NULL DEFAULT false,
	last_name varchar(255) NULL,
	address_line_1 text NOT NULL,
	administrative_area text NOT NULL,
	locality text NOT NULL,
	postal_code text NOT NULL,
	country text NOT NULL,
	tag varchar(255) NULL DEFAULT NULL::character varying,
	date_of_birth date NOT NULL,
	government_id_type varchar NOT NULL,
	government_id_last4 varchar(4) NOT NULL,
	government_id_state varchar(2) NULL,
	identity_verified bool NOT NULL,
	CONSTRAINT users_pkey PRIMARY KEY (id)
);

